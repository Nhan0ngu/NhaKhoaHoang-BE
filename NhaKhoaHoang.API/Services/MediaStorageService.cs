
using Azure;
using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;
using Microsoft.Extensions.Options;
using NhaKhoaHoang.API.Configuration;

namespace NhaKhoaHoang.API.Services;

public sealed class MediaStorageService
{
    private readonly BlobContainerClient _container;
    private readonly BlobStorageOptions _options;

    public MediaStorageService(
        IOptions<BlobStorageOptions> options)
    {
        _options = options.Value;

        if (string.IsNullOrWhiteSpace(
            _options.ConnectionString))
        {
            throw new InvalidOperationException(
                "BlobStorage:ConnectionString is missing.");
        }

        if (string.IsNullOrWhiteSpace(
            _options.ContainerName))
        {
            throw new InvalidOperationException(
                "BlobStorage:ContainerName is missing.");
        }

        if (_options.MaxFileSizeBytes <= 0)
        {
            throw new InvalidOperationException(
                "Invalid MaxFileSizeBytes.");
        }

        var service = new BlobServiceClient(
            _options.ConnectionString);

        _container = service.GetBlobContainerClient(
            _options.ContainerName);
    }

    public long MaxFileSizeBytes =>
        _options.MaxFileSizeBytes;

    public async Task<UploadedBlob> UploadAsync(
        Stream content,
        string extension,
        string contentType,
        CancellationToken ct)
    {
        // File names are generated by the server.
        var blobKey =
            $"website/{DateTime.UtcNow:yyyy/MM}/" +
            $"{Guid.NewGuid():N}{extension}";

        var blob = _container.GetBlobClient(blobKey);

        await blob.UploadAsync(
            content,
            new BlobUploadOptions
            {
                HttpHeaders = new BlobHttpHeaders
                {
                    ContentType = contentType
                }
            },
            ct);

        return new UploadedBlob(
            blobKey,
            blob.Uri.ToString());
    }

    public async Task DeleteAsync(
        string blobKey,
        CancellationToken ct)
    {
        if (string.IsNullOrWhiteSpace(blobKey))
        {
            throw new ArgumentException(
                "Blob key is required.");
        }

        await _container
            .GetBlobClient(blobKey)
            .DeleteIfExistsAsync(
                DeleteSnapshotsOption.IncludeSnapshots,
                cancellationToken: ct);
    }

    public sealed record UploadedBlob(
        string StorageKey,
        string PublicUrl);
}
